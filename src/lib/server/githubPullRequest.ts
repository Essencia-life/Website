import { env } from '$env/dynamic/private';
import type { components } from '@octokit/openapi-types';
import type { EventDraft, RepoState } from './tallyEvent';

// Response types of the GitHub REST API (type-only package, nothing ends up in the bundle).
type Schemas = components['schemas'];

/**
 * Creates a pull request the way Sveltia CMS does in the editorial workflow:
 * branch `cms/<collection>/<slug>`, one commit with the entry file and its assets,
 * pull request titled like the commit and labelled with the entry status.
 *
 * Needs `TALLY_GITHUB_TOKEN`: a fine-grained personal access token for this repository
 * with "Contents" and "Pull requests" set to read and write.
 */

const REPO = 'Essencia-life/Website';
const BASE_BRANCH = 'main';
const PULL_REQUEST_BODY = 'Automatically generated by Sveltia CMS';
// Submissions from the public form start "In Review". Use `sveltia-cms/draft` (and
// `draft: true` below) to start them as drafts instead.
const STATUS_LABEL = 'sveltia-cms/pending_review';
const AS_DRAFT = false;

export type LoadedRepoState = RepoState & { baseSha: string; treeSha: string };

const request = async <T>(method: string, path: string, body?: unknown): Promise<T> => {
	const token = env.TALLY_GITHUB_TOKEN;
	if (!token) throw new Error('TALLY_GITHUB_TOKEN is not configured.');

	const response = await fetch(`https://api.github.com${path}`, {
		method,
		headers: {
			Authorization: `Bearer ${token}`,
			Accept: 'application/vnd.github+json',
			'X-GitHub-Api-Version': '2022-11-28',
			'User-Agent': 'essencia-website-tally-webhook',
			...(body === undefined ? {} : { 'Content-Type': 'application/json' })
		},
		body: body === undefined ? undefined : JSON.stringify(body),
		signal: AbortSignal.timeout(20_000)
	});

	if (!response.ok) {
		const detail = (await response.text()).slice(0, 300);
		throw new Error(`GitHub ${method} ${path} failed with ${response.status}: ${detail}`);
	}

	return (response.status === 204 ? undefined : await response.json()) as T;
};

/** Reads the base branch plus the file paths and CMS branches that already exist. */
export const loadRepoState = async (): Promise<LoadedRepoState> => {
	const ref = await request<Schemas['git-ref']>(
		'GET',
		`/repos/${REPO}/git/ref/heads/${BASE_BRANCH}`
	);
	const baseSha = ref.object.sha;
	const commit = await request<Schemas['git-commit']>(
		'GET',
		`/repos/${REPO}/git/commits/${baseSha}`
	);
	const treeSha = commit.tree.sha;

	const [tree, refs] = await Promise.all([
		request<Schemas['git-tree']>('GET', `/repos/${REPO}/git/trees/${treeSha}?recursive=1`),
		request<Schemas['git-ref'][]>('GET', `/repos/${REPO}/git/matching-refs/heads/cms/events`)
	]);
	if (tree.truncated) throw new Error('The repository tree is too large to list.');

	return {
		baseSha,
		treeSha,
		paths: new Set(tree.tree.flatMap((entry) => (entry.path ? [entry.path] : []))),
		branches: new Set(refs.map((entry) => entry.ref.replace(/^refs\/heads\//, '')))
	};
};

/** Commits the draft to a new branch and opens the pull request. Returns its URL. */
export const createEventPullRequest = async (
	state: LoadedRepoState,
	draft: EventDraft,
	downloads: Map<string, Uint8Array>
): Promise<string> => {
	const tree = await Promise.all(
		draft.files.map(async (file) => {
			const blob =
				'content' in file
					? await request<Schemas['short-blob']>('POST', `/repos/${REPO}/git/blobs`, {
							content: file.content,
							encoding: 'utf-8'
						})
					: await request<Schemas['short-blob']>('POST', `/repos/${REPO}/git/blobs`, {
							content: Buffer.from(downloads.get(file.path) ?? new Uint8Array()).toString('base64'),
							encoding: 'base64'
						});
			return { path: file.path, mode: '100644', type: 'blob', sha: blob.sha };
		})
	);

	const newTree = await request<Schemas['git-tree']>('POST', `/repos/${REPO}/git/trees`, {
		base_tree: state.treeSha,
		tree
	});
	const commit = await request<Schemas['git-commit']>('POST', `/repos/${REPO}/git/commits`, {
		message: draft.message,
		tree: newTree.sha,
		parents: [state.baseSha]
	});

	// If this fails (e.g. the branch exists), nothing has been created yet, so nothing to clean up.
	await request('POST', `/repos/${REPO}/git/refs`, {
		ref: `refs/heads/${draft.branch}`,
		sha: commit.sha
	});

	let pullNumber: number | undefined;
	try {
		const pull = await request<Schemas['pull-request']>(
			'POST',
			`/repos/${REPO}/pulls`,
			{
				title: draft.message,
				head: draft.branch,
				base: BASE_BRANCH,
				body: PULL_REQUEST_BODY,
				draft: AS_DRAFT
			}
		);
		pullNumber = pull.number;

		// Without its status label Sveltia CMS would not show the pull request on its board.
		await request('POST', `/repos/${REPO}/issues/${pull.number}/labels`, {
			labels: [STATUS_LABEL]
		});

		// Traceability and hints for the reviewer. Contact details stay in Tally, as this repo is public.
		const notes = [`Submitted via the Tally form (submission \`${draft.submissionId}\`).`];
		if (draft.warnings.length > 0) {
			notes.push('', 'Please check:', ...draft.warnings.map((warning) => `- ${warning}`));
		}
		await request('POST', `/repos/${REPO}/issues/${pull.number}/comments`, {
			body: notes.join('\n')
		}).catch((error) => console.error('[tally-webhook] could not add comment', error));

		return pull.html_url;
	} catch (error) {
		if (pullNumber !== undefined) {
			await request('PATCH', `/repos/${REPO}/pulls/${pullNumber}`, { state: 'closed' }).catch(
				() => {}
			);
		}
		await request('DELETE', `/repos/${REPO}/git/refs/heads/${draft.branch}`).catch(() => {});
		throw error;
	}
};
